    private void jButton6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton6ActionPerformed

        listarCamposTextos();
        if (validarCamposVacios()) {
            if (validarCamposNumericos()) {
                fechaAutorizacion = Instant.ofEpochMilli(jDateChooser1.getDate().getTime()).atZone(ZoneId.systemDefault()).toLocalDate();
                if (fechaAutorizacion.getDayOfMonth() <= 20) {
                    cg.enviarSolicitanteBanco(ingresoNumeroPrestamos5.getText(), ingresoNumeroPrestamos6.getText(), ingresoNumeroPrestamos1.getText(), ingresoNumeroPrestamos2.getText(), ingresoNumeroPrestamos3.getText(), ingresoNumeroPrestamos4.getText());
                    cg.enviarPrestamoBanco(ingresoNumeroPrestamos7.getText(), ingresoNumeroPrestamos.getText(), fechaAutorizacion);
                } else {
                    JOptionPane.showMessageDialog(null, "Los préstamos solo se pueden autorizar en los primeros 20 días del mes.", "!Fecha de autorizacion erronea¡", 1);
                    //return;
                }
            }
        } else {
            JOptionPane.showMessageDialog(null, "Ingrese la informacion completa y correcta del prestamo", "!Informacion incompleta¡", 1);
        }

    }//GEN-LAST:event_jButton6ActionPerformed

