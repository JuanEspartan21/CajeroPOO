    public boolean validarCamposVacios() {
        for (int i = 0; i < jtextos.size(); i++) {
            if (jtextos.get(i) == null || jtextos.get(i).toString() == null || jtextos.get(i).toString().trim().isEmpty()) {
                return false;
            }
        }
        return true;
    }

